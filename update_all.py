def merge_rsi_result(fund, result):
    for key in ('asset_name', 'data_type', 'data_type_label', 'total_records',
                'date_range', 'fund_years', 'data_quality', 'latest', 'recent_rsi',
                'stats', 'extremes', 'backtest', 'predict', 'multi_tf_rsi',
                'rolling_backtest', 'weekly_rsi'):
        if key not in result:
            continue
        # asset_name 不允许用 fallback 格式（如 私募/基金+数字）覆盖已有真名，
        # 防止取名字段瞬时失败把好名字冲掉
        if key == 'asset_name':
            new_name = result[key]
            cur_name = fund.get('asset_name', '')
            if re.match(r'^(基金|香港基金|私募基金)\d+$', new_name or '') and cur_name and not re.match(r'^(基金|香港基金|私募基金)\d+$', cur_name):
                continue
        fund[key] = result[key]
    fund['latest']['rsi_updated'] = now_str()


def main():
    parser = argparse.ArgumentParser(description='一键更新所有标的分析 (RSI + 技术分析)')
    parser.add_argument('--skip-us', '--skip-us-stock', action='store_true',
                        help='跳过美股 (美股盘后/非交易日)')
    parser.add_argument('--only', nargs='+',
                        help='只更新指定类型: cn_fund cn_stock us_stock hk_fund cn')
    parser.add_argument('--no-llm', action='store_true', help=argparse.SUPPRESS)  # 兼容旧命令；LLM 已停用
    parser.add_argument('--no-tech', action='store_true', help='跳过技术分析，只更新数据和 RSI')
    parser.add_argument('--data-only', action='store_true', help='只更新数据+RSI (阶段1)')
    parser.add_argument('--force', action='store_true', help='强制重新获取数据')
    parser.add_argument('--no-open', action='store_true', help='不自动打开浏览器')
    parser.add_argument('--symbols', nargs='+', help='只更新指定代码的标的 (如 --symbols 512890 515300 007280)')
    parser.add_argument('--categories', nargs='+',
                        help='按 tab 分类纳入(commodity/private/cn_stock/us_stock/dividend/bond/global/...),'
                             '与 --symbols 取并集;新增标的加到 index.html 对应 tab 的 CODES 集合即自动纳入')
    args = parser.parse_args()

    run_data = True
    run_tech = not args.no_tech and not args.data_only

    print('=' * 55, flush=True)
    print(f'RSI Analysis 一键更新  [{now_str()}]', flush=True)
    if args.skip_us:
        print('模式: 跳过美股', flush=True)
    elif args.only:
        print(f'模式: 只更新 {", ".join(args.only)}', flush=True)
    if args.no_tech or args.data_only:
        print('阶段: 数据更新 + RSI (跳过技术分析)', flush=True)
    else:
        print('阶段: 数据更新 + RSI → 技术分析 (LLM 已停用)', flush=True)
    print('=' * 55, flush=True)

    backup()
    funds = load_funds()
    
    # 自动发现新标的：对比 fund_watchlist.json
    funds, new_count = sync_watchlist(funds)
    if new_count > 0:
        save_funds(funds)  # 立即保存，避免后续出错丢失
    
    meta = load_meta()
    total = len(funds)
    target_count = 0
    ok = 0
    fail = 0

    for idx, fund in enumerate(funds):
        symbol = fund['symbol']
        name = fund.get('name', fund.get('asset_name', symbol)) or symbol
        data_type = fund.get('data_type', '')
        prefix = TYPE_PREFIXES.get(data_type, 'fund')

        if should_skip(fund, args):
            continue

        target_count += 1
        label = f'[{target_count}] {symbol} ({name[:15]})'
        print(f'  {label}', end='', flush=True)

        ta_json = os.path.join(RESULT_DIR, f'{prefix}_{symbol}_full_ta.json')

        try:
            snapshot = None
            if run_data or run_tech:
                snapshot = fetch_data(symbol, data_type)
                if snapshot[0] is None:
                    print(' ❌数据失败', flush=True)
                    fail += 1
                    continue
                df, price_col, asset_name = snapshot
                print(' [同一快照]', end='', flush=True)

            # === 阶段1: RSI，直接复用本批次快照 ===
            if run_data:
                analyzer = RSIAnalyzer(symbol)
                rsi_result = analyzer.analyze(snapshot)
                if not rsi_result:
                    print(' ❌RSI失败', flush=True)
                    fail += 1
                    continue
                merge_rsi_result(fund, rsi_result)
                analyzer.save_files(rsi_result)
                print(' [RSI✓]', end='', flush=True)

            # === 阶段2: 技术指标，继续复用同一快照且总是刷新 ===
            if run_tech:
                ta = run_technical_analysis(df, price_col, data_type)
                if 'error' in ta:
                    print(' ❌分析错误', flush=True)
                    fail += 1
                    continue
                ta.update(symbol=symbol, asset_name=asset_name, ta_updated=now_str())
                with open(ta_json, 'w', encoding='utf-8') as f:
                    json.dump(ta, f, ensure_ascii=False, indent=2, default=str)
                fund['full_ta_summary'] = build_ta_summary(ta, fund)
                fund['bollinger'] = build_dashboard_bollinger(
                    ta, (fund.get('latest') or {}).get('rsi', 50))
                sig = ta.get('signal_summary', {})
                report = format_technical_report(ta, name)
                print(' [技术✓]', end='', flush=True)
            # 组装报告
            if run_tech:
                fund['full_ta_report'] = report

            ok += 1
            print(f' ✓', flush=True)

            # 每10个保存一次
            if ok % 10 == 0:
                save_funds(funds)
                print(f'  >>> 保存 {ok}/{target_count} <<<', flush=True)

        except Exception as e:
            print(f' ❌异常: {e}', flush=True)
            fail += 1

    # === 阶段4: 晨星持有人 + 规模变动（仅红利/固收/QDII）===
    cat_sets = _load_category_sets()

    ms_ok = 0
    ms_fail = 0
    ms_skip = 0
    print('', flush=True)
    print('--- 晨星持有人 + 规模变动 (仅红利/固收/QDII) ---', flush=True)
    for idx, fund in enumerate(funds):
        symbol = fund.get('symbol', '')
        # 晨星阶段也遵循本次批次筛选，避免 --symbols 等选项意外触发全量网络抓取。
        if should_skip(fund, args):
            continue
        if not (len(symbol) == 6 and symbol[0] in '0123456789'):
            continue
        if _py_get_category(fund, cat_sets) not in MORNINGSTAR_CATEGORIES:
            ms_skip += 1
            continue
        try:
            ms_data = _fetch_ms_with_retry(symbol)
            if ms_data:
                fund['morningstar_holders'] = ms_data
                fund['holders_updated'] = now_str()
                ms_ok += 1
                sf = ms_data.get('manager_funds', {}).get('sibling_funds', [])
                sh = ms_data.get('scale_history', [])
                print(f'  [{symbol}] ✓ 兄弟:{len(sf)} 规模:{len(sh)}Q', flush=True)
            else:
                ms_fail += 1
                print(f'  [{symbol}] 失败(重试3次)', flush=True)
            time.sleep(1.5)
        except Exception as e:
            ms_fail += 1
            print(f'  [{symbol}] 异常: {e}', flush=True)
    print(f'  跳过(非红利/固收/QDII): {ms_skip}', flush=True)

    # 最终保存
    save_funds(funds)

    # 更新 meta
    meta['last_update'] = now_str()
    meta['last_count'] = ok
    meta['last_fail'] = fail
    meta['last_args'] = ' '.join(sys.argv[1:])
    meta.pop('last_llm_ok', None)
    save_meta(meta)

    print('', flush=True)
    print('=' * 55, flush=True)
    print(f'更新完成! [{now_str()}]', flush=True)
    print(f'  目标: {target_count}  成功: {ok}  失败: {fail}', flush=True)
    print(f'  晨星: {ms_ok} 成功, {ms_fail} 失败, 跳过 {ms_skip} (非红利/固收/QDII)', flush=True)
    print(f'  文件: {EMBEDDED_JS}', flush=True)
    print(f'  日志: {META_FILE}', flush=True)
    print('=' * 55, flush=True)

    if not args.no_open:
        os.system(f'open {os.path.join(RESULT_DIR, "index.html")}')

    return ok, fail


if __name__ == '__main__':
    main()
