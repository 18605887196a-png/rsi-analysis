WATCHLIST_JSON = os.path.join(RESULT_DIR, 'fund_watchlist.json')
META_FILE = os.path.join(RESULT_DIR, 'update_meta.json')

TYPE_PREFIXES = {
    'us_stock': 'us_stock',
    'cn_stock': 'cn_stock',
    'cn_fund': 'fund',
    'hk_fund': 'hk_fund',
    'cn_auto': 'fund',
    'cn_bond': 'fund',
    'private_fund': 'fund',
}

US_TYPES = {'us_stock'}
CN_TYPES = {'cn_fund', 'cn_stock', 'cn_auto', 'cn_bond', 'private_fund'}
HK_TYPES = {'hk_fund'}


def now_str():
    return datetime.now().strftime('%Y-%m-%d %H:%M:%S')


# 晨星抓取范围：只挑 红利 + 固收(纯债/固收精选) + QDII
MORNINGSTAR_CATEGORIES = {'dividend', 'bond_tier1', 'bond', 'global'}


def _load_category_sets():
    """从 result/index.html 解析分类常量集合，与 JS 端 getCategory 共享单一数据源"""
    sets = {}
    path = os.path.join(RESULT_DIR, 'index.html')
    try:
        text = open(path, 'r', encoding='utf-8').read()
        for name in ('BROAD_CODES', 'QUALITY_CODES', 'HK_CODES', 'DIVIDEND_CODES',
                     'THEMATIC_CODES', 'BOND_CODES', 'BOND_TIER1', 'COMMODITY_CODES',
                     'GLOBAL_CODES', 'PRIVATE_CODES'):
            m = re.search(r'const\s+' + name + r'\s*=\s*new\s+Set\(\[([^\]]*)\]\)', text, re.S)
            sets[name] = set(re.findall(r"'(\d+)'", m.group(1))) if m else set()
    except Exception:
        pass
    return sets


def _py_get_category(fund, sets):
    """Python 版 getCategory（与 index.html 逻辑一致）"""
    sym = fund.get('symbol', '')
    dt = fund.get('data_type', '')
    if sym in sets.get('PRIVATE_CODES', set()): return 'private'
    if sym in sets.get('BROAD_CODES', set()): return 'broad'
    if sym in sets.get('QUALITY_CODES', set()): return 'quality'
    if sym in sets.get('HK_CODES', set()): return 'hk'
    if sym in sets.get('DIVIDEND_CODES', set()): return 'dividend'
    if sym in sets.get('THEMATIC_CODES', set()): return 'thematic'
    bond, tier1 = sets.get('BOND_CODES', set()), sets.get('BOND_TIER1', set())
    if sym in bond and sym not in tier1: return 'bond'
    if sym in tier1: return 'bond_tier1'
    if sym in sets.get('COMMODITY_CODES', set()): return 'commodity'
    if sym in sets.get('GLOBAL_CODES', set()): return 'global'
    if dt == 'us_stock': return 'us_stock'
    if dt == 'cn_stock': return 'cn_stock'
    return 'other'


def _fetch_ms_with_retry(symbol, attempts=3):
    """单只基金抓取，失败重试，退避 2/4/8s"""
    for k in range(attempts):
        try:
            data = fetch_morningstar_holders(symbol)
            if data:
                return data
        except Exception:
            pass
        if k < attempts - 1:
            time.sleep(2 * (k + 1))
    return None


def load_funds():
    if not os.path.exists(EMBEDDED_JS):
        return []
    with open(EMBEDDED_JS, 'r', encoding='utf-8') as f:
        c = f.read()
    j = c.split('var EMBEDDED_FUNDS = ', 1)[1].rstrip().rstrip(';')
    return json.loads(j)


def save_funds(funds):
    js_content = '// Auto-generated by RSI analyzer - DO NOT EDIT\n'
    js_content += 'var EMBEDDED_FUNDS = '
    js_content += json.dumps(funds, ensure_ascii=False)
    js_content += ';\n'
    # 双文件同步写入：index.html 先加载 data.js 再加载 embedded_data.js 覆盖，
    # 两个文件必须一致，否则浏览器可能看到旧 data.js。
    for path in (EMBEDDED_JS, DATA_JS):
        with open(path, 'w', encoding='utf-8') as f:
            f.write(js_content)


def load_meta():
    if os.path.exists(META_FILE):
        with open(META_FILE, 'r') as f:
            return json.load(f)
    return {}


def save_meta(meta):
    with open(META_FILE, 'w') as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)


def sync_watchlist(funds):
    """对比 fund_watchlist.json 和 embedded_data.js，自动添加新标的。
    
    如果 watchlist 中有但 funds 中没有的 symbol，自动用 detect_type 获取类型，
    用 get_cn_fund_info / get_cn_stock_name 等获取名称，然后添加到 funds 中。
    """
    if not os.path.exists(WATCHLIST_JSON):
        print(f'⚠️ 未找到 {WATCHLIST_JSON}，跳过自动发现', flush=True)
        return funds, 0
    
    with open(WATCHLIST_JSON, 'r', encoding='utf-8') as f:
        watchlist = json.load(f)

    label_map = {
        'us_stock': '美股',
        'cn_stock': 'A股股票',
        'cn_fund': 'A股基金',
        'cn_auto': 'A股基金',
        'hk_fund': '香港基金',
        'cn_bond': '纯债基金',
        'private_fund': '私募基金',
    }

    existing_symbols = {fund['symbol'] for fund in funds}
    new_entries = []

    for item in watchlist:
        sym = item['symbol']
        if sym in existing_symbols:
            continue
        # 优先使用 watchlist 显式声明的类型；否则自动检测
        data_type = item.get('data_type') or detect_type(sym)[0]
        name = item.get('name', '')
        if not name:
            try:
                if data_type == 'cn_stock':
                    from data_fetcher import get_cn_stock_name
                    name = get_cn_stock_name(sym)
                elif data_type == 'private_fund':
                    from data_fetcher import get_gaoduan_fund_info
                    name = get_gaoduan_fund_info(sym)
                elif data_type in ('cn_fund', 'cn_auto'):
                    from data_fetcher import get_cn_fund_info
                    name = get_cn_fund_info(sym)
                elif data_type == 'hk_fund':
                    from data_fetcher import get_hk_fund_name
                    name = get_hk_fund_name(sym)
            except Exception:
                pass
            if not name:
                name = f"基金{sym}" if data_type in ('cn_fund', 'cn_auto', 'hk_fund', 'private_fund') else sym
        new_entries.append({
            'symbol': sym,
            'asset_name': name,
            'data_type': data_type,
            'data_type_label': label_map.get(data_type, '未知'),
        })
        print(f'  [新标的] {sym} ({name}) type={data_type}', flush=True)

    if new_entries:
        funds.extend(new_entries)
        print(f'  共添加 {len(new_entries)} 个新标的', flush=True)

    return funds, len(new_entries)


def backup():
    if os.path.exists(EMBEDDED_JS) and not os.path.exists(BACKUP_JS):
        import shutil
        shutil.copy2(EMBEDDED_JS, BACKUP_JS)


def should_skip(fund, args):
    data_type = fund.get('data_type', '')
    if args.skip_us and data_type in US_TYPES:
        return True
    # --symbols / --categories 并集纳入:命中任一即更新;都未传则不以此过滤。
    # 新增标的加到 index.html 对应 tab 的 CODES 集合(或 watchlist 声明 cn_stock/us_stock)
    # 即自动纳入 --categories,无需改本脚本/批次列表。
    if args.symbols or args.categories:
        sym = fund.get('symbol', '')
        in_sym = bool(args.symbols) and sym in set(args.symbols)
        in_cat = False
        if args.categories:
            cat_sets = getattr(should_skip, '_cat_sets', None)
            if cat_sets is None:
                cat_sets = _load_category_sets()
                should_skip._cat_sets = cat_sets
            in_cat = _py_get_category(fund, cat_sets) in set(args.categories)
        if not (in_sym or in_cat):
            return True
    if args.only:
        # 私募/高端理财：按 PRIVATE_CODES 成员过滤（这类标的 data_type 仍是 cn_auto，
        # 靠分类集合识别，而非 data_type）
        if 'private' in args.only:
            cat_sets = getattr(should_skip, '_cat_sets', None)
            if cat_sets is None:
                cat_sets = _load_category_sets()
                should_skip._cat_sets = cat_sets
            private_codes = cat_sets.get('PRIVATE_CODES', set())
            if fund.get('symbol', '') not in private_codes:
                return True
            return False
        allowed = set()
        for t in args.only:
            if t == 'us_stock': allowed |= US_TYPES
            elif t == 'cn_fund': allowed.add('cn_fund')
            elif t == 'cn_stock': allowed.add('cn_stock')
            elif t == 'cn_auto': allowed.add('cn_auto')
            elif t == 'cn_bond': allowed.add('cn_bond')
            elif t == 'hk_fund': allowed |= HK_TYPES
            elif t == 'cn': allowed |= CN_TYPES
        if data_type not in allowed:
            return True
    return False


